import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { RuntimeIpc } from "../../packages/mcp/dist/ipc.js";

const root = process.env.XALLOR_TEST_CLUSTER;
assert(root && fs.readFileSync(path.join(root, ".owner"), "utf8") === "runtime-cluster");
const alice = JSON.parse(fs.readFileSync(path.join(root, "alice.json"), "utf8"));
const bob = JSON.parse(fs.readFileSync(path.join(root, "bob.json"), "utf8"));
const run = promisify(execFile);
const cli = (...args) => run(process.env.XALLOR_TEST_CLI, args, { env: process.env, windowsHide: true, timeout: 20000 });
const admin = (...args) => cli("relay", "--data", path.join(root, "relay"), "principal", ...args);
const results = [];
const client = new RuntimeIpc();
await client.connect();
const info = () => client.call("info", { device_id: process.env.XALLOR_TEST_TARGET });
const pass = name => results.push({ name, status: "pass" });
try {
  assert.equal((await info()).ok, true);
  await admin("revoke", "--credential", alice.credential_id);
  assert.equal((await info()).code, "unauthorized", "cached Relay link bypassed token revocation");
  const doctor = await client.call("doctor", { device_id: process.env.XALLOR_TEST_TARGET });
  assert.equal(doctor.ok, true);
  assert(doctor.result.checks.some(check => check.code === "unauthorized"), "diagnostics silently used anonymous access");
  pass("revocation_rechecks_cached_link_and_diagnostics");
  await cli("account", "use", "--credential-file", path.join(root, "bob.json"));
  assert.equal((await info()).ok, true);
  await admin("membership", "--membership", bob.membership_id, "--active=false");
  assert.equal((await info()).code, "unauthorized");
  await admin("membership", "--membership", bob.membership_id, "--active=true");
  assert.equal((await info()).code, "unauthorized", "membership restoration resurrected an old binding");
  await cli("account", "use", "--credential-file", path.join(root, "bob.json"));
  assert.equal((await info()).ok, true);
  pass("member_generation_requires_fresh_handshake");
  const renewed = JSON.parse((await admin("issue", "--membership", bob.membership_id)).stdout);
  assert.equal(renewed.principal_id, bob.principal_id);
  assert.equal(renewed.tenant_id, bob.tenant_id);
  assert.notEqual(renewed.credential_id, bob.credential_id);
  fs.writeFileSync(path.join(root, "renewed.json"), JSON.stringify(renewed));
  await cli("account", "use", "--credential-file", path.join(root, "renewed.json"));
  await admin("revoke", "--credential", bob.credential_id);
  assert.equal((await info()).ok, true, "renewed credential inherited revocation of another credential");
  pass("renewal_preserves_principal_and_independent_revocation");
  await cli("account", "clear");
  assert.equal((await info()).ok, true, "explicit anonymous shared access stopped working");
  pass("explicit_clear_keeps_unclaimed_device_sharing");
  fs.writeFileSync(path.join(root, "principal-results.json"), JSON.stringify(results));
  console.log("Principal lifecycle scenarios passed");
} finally { client.close(); }
